param(
    [string]$Fxc = ""
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

# Regenerates image_pass_shaders.h from image_pass.hlsl. The DLL build uses the
# committed header, so neither CI nor players need a shader compiler.
$source = Join-Path $PSScriptRoot "image_pass.hlsl"
$output = Join-Path $PSScriptRoot "image_pass_shaders.h"
if ([string]::IsNullOrWhiteSpace($Fxc)) {
    $Fxc = Get-ChildItem -Path "${env:ProgramFiles(x86)}\Windows Kits\10\bin\*\x64\fxc.exe" |
        Sort-Object FullName | Select-Object -Last 1 -ExpandProperty FullName
}
if (-not $Fxc -or -not (Test-Path -LiteralPath $Fxc -PathType Leaf)) {
    throw "fxc.exe not found; pass -Fxc <path>."
}

$temp = Join-Path ([System.IO.Path]::GetTempPath()) "rotk-image-shaders-$PID"
New-Item -ItemType Directory -Path $temp -Force | Out-Null
try {
    $parts = @()
    foreach ($stage in @(@("vs_4_0", "vs_main", "image_vs"), @("ps_4_0", "ps_main", "image_ps"))) {
        $blob = Join-Path $temp "$($stage[2]).cso"
        & $Fxc /nologo /T $stage[0] /E $stage[1] /O3 /Qstrip_reflect /Qstrip_debug /Qstrip_priv /Fo $blob $source | Out-Null
        if ($LASTEXITCODE -ne 0) { throw "fxc failed for $($stage[1])." }
        $bytes = [System.IO.File]::ReadAllBytes($blob)
        $lines = for ($i = 0; $i -lt $bytes.Length; $i += 16) {
            "    " + (($bytes[$i..([Math]::Min($i + 15, $bytes.Length - 1))] | ForEach-Object { "0x{0:x2}," -f $_ }) -join "")
        }
        $parts += "static const BYTE $($stage[2])[] = {`n$($lines -join "`n")`n};"
    }
    $text = "/* Generated by build-image-shaders.ps1 from image_pass.hlsl; do not edit. */`n" +
        "#ifndef ROTK_IMAGE_PASS_SHADERS_H`n#define ROTK_IMAGE_PASS_SHADERS_H`n" +
        ($parts -join "`n") + "`n#endif`n"
    [System.IO.File]::WriteAllText($output, $text, [System.Text.Encoding]::ASCII)
} finally {
    Remove-Item -LiteralPath $temp -Recurse -Force -ErrorAction SilentlyContinue
}
Write-Host "Wrote $output"
